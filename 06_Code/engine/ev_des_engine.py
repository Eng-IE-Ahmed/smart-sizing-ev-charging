"""EV charging DES engine - IE3753 project (Dataset , Caltech ACN-Data, Mar-May 2019).  Version 2.

Mirrors the Excel workbook exactly when run with --service AB (= v1, same cleaning rules, inputs, formulas):
  * Arrivals: non-homogeneous Poisson process, 48 half-hour weekday rates (arrivals / 65 weekdays).
    Generated by inverting the cumulative rate: L_i = L_{i-1} - ln(1-U1_i), t_i = Lambda^-1(L_i).
  * c identical chargers, one FIFO queue:  start_j = max(a_j, j-c th smallest earlier departure).
  * One replication = 65 weekdays (1,560 h) run back to back, starting empty.
  * Common random numbers: replication r uses streams default_rng([r,1]) (arrivals) and ([r,2]) (service)
    for every option AND every service model; each car gets exactly one service uniform U2.

Service (= connection time at the charger) models, --service:
  AB        v1: empirical inverse transform per arrival class (A = arrival 05:00-11:59, B = otherwise),
            weekday sessions <= 24 h:  X = x_(ceil(U2*n)).
  band      empirical inverse transform per arrival band (6 bands, local hour: 05-07, 08-09, 10-11, 12-15,
            16-20, 21-04), weekday sessions <= 24 h.
  band_long same as band, but the pools include weekday stays > 24 h (DEFAULT; plan decision ).
  band_long_opt  as band_long, with the optimal contiguous 6-band partition of R2 (00-06, 07-09, 10-12, 13,
            14-20, 21-23); sensitivity model (reviewer decision under ).
  mixA_lnB  class A: 4-component lognormal mixture (GMM on ln x); class B: lognormal (MLE, loc = 0);
            both fitted to the <= 24 h pools and truncated at 24 h; X = F^-1(U2 * F(24)).
  jointGMM  bivariate GMM (K = 10 by default = BIC minimum; --joint-k 8 for the reviewer's K) on (arrival hour, ln dwell), <= 24 h pool; X drawn from the
            conditional distribution of ln dwell given the arrival hour, truncated at 24 h, by inversion
            with the same U2.
  Fitted models use random_state = SEED (20261114).  Inversion is by 60-step bisection on ln x.

Arrivals: pooled weekday rates (default) or --rates-file data/derived/rates_designday.csv (design day, Tue-Wed).
API: draw() -> arrivals + services of one replication (independent of c); run_queue() -> outputs for one c;
     replicate() = draw + run_queue (v1 signature); extra=True adds the R7 outputs (extra_outputs()).

Run:  python ev_des_engine.py [path_to_json] [--service AB|band|band_long|band_long_opt|mixA_lnB|jointGMM]
      [--joint-k K] [--rates-file csv] [--out file]
      --service AB writes engine_outputs.json (identical to v1); other models write
      engine_outputs_<service>.json unless --out is given.
"""
import json, heapq, datetime as dt
import numpy as np
import pandas as pd

import sys, pathlib
_DEFAULT_DATA = pathlib.Path(__file__).resolve().parents[2] / "08_Data" / "raw" / "acn_caltech_2019-03-01_2019-05-31.json"
DATA = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else str(_DEFAULT_DATA)
HOLIDAY = dt.date(2019, 5, 27)      # Memorial Day (US federal holiday) - treated like a weekend
NDAYS = 65                          # weekdays in the period after removing the holiday
MAXDUR = 24.0                       # h; longer sessions = long-term parking, excluded from the v1 service pool
TARGET = 15.0                       # min; waiting-time target for the risk measure
HORIZON = NDAYS * 24.0              # h
SEED = 20261114                     # random_state of every fitted (parametric) service model
SERVICES = ("AB", "band", "band_long", "band_long_opt", "mixA_lnB", "jointGMM")
BANDS = ((5, 8), (8, 10), (10, 12), (12, 16), (16, 21))    # [start, end) local hour; band 5 = 21:00-04:59
BAND_LABELS = ("05-07", "08-09", "10-11", "12-15", "16-20", "21-04")
# Optimal contiguous 6-band partition of the hours (R2, max R^2 of ln dwell, >= 50 sessions/band, incl. long stays)
HOUR_BAND_OPT = np.array([0] * 7 + [1] * 3 + [2] * 3 + [3] + [4] * 7 + [5] * 3)
BAND_LABELS_OPT = ("00-06", "07-09", "10-12", "13", "14-20", "21-23")
JOINT_K = 10                        # joint GMM components (BIC minimum, R2; reviewer decision under )


def load():
    d = json.load(open(DATA))
    rows = [dict(conn=i["connectionTime"], disc=i["disconnectTime"]) for i in d["_items"]]
    df = pd.DataFrame(rows)
    for c in ["conn", "disc"]:
        df[c] = (pd.to_datetime(df[c], format="%a, %d %b %Y %H:%M:%S GMT", utc=True)
                 .dt.tz_convert("America/Los_Angeles").dt.tz_localize(None))
    df = df.sort_values("conn").reset_index(drop=True)
    df["date"] = df.conn.dt.date
    df["weekday"] = (df.conn.dt.dayofweek < 5) & (df.date != HOLIDAY)
    df["dur"] = (df.disc - df.conn).dt.total_seconds() / 3600   # local clock, same as Excel
    df["hr"] = df.conn.dt.hour
    df["slot"] = (df.conn.dt.hour * 2 + df.conn.dt.minute // 30)
    return df


def inputs(df):
    W = df[df.weekday]
    rates = np.array([(W.slot == k).sum() / NDAYS for k in range(48)])     # arrivals per half hour
    pool = W[W.dur <= MAXDUR]
    A = np.sort(pool.dur[(pool.hr >= 5) & (pool.hr < 12)].values)
    B = np.sort(pool.dur[~((pool.hr >= 5) & (pool.hr < 12))].values)
    return rates, A, B


def band_of(hour, opt=False):
    """Arrival band 0..5 of a local hour of day (decimal or integer); opt=True uses HOUR_BAND_OPT."""
    h = np.asarray(hour, float)
    if opt:
        return HOUR_BAND_OPT[np.floor(h).astype(int) % 24]
    return np.select([(h >= a) & (h < b) for a, b in BANDS], list(range(len(BANDS))), len(BANDS))


def band_pools(df, long_stays, opt=False):
    """Sorted weekday dwell pools (h) by arrival band; long_stays=True keeps stays > 24 h."""
    W = df[df.weekday]
    if not long_stays:
        W = W[W.dur <= MAXDUR]
    b = band_of(W.hr.values, opt)
    return [np.sort(W.dur.values[b == i]) for i in range(len(BANDS) + 1)]


def load_rates(path):
    """48 half-hour rates from a CSV (column rate_designday, else the last numeric 'rate*' column)."""
    t = pd.read_csv(path)
    col = "rate_designday" if "rate_designday" in t else [c for c in t.columns if c.startswith("rate")][-1]
    r = t[col].to_numpy(float)
    assert len(r) == 48
    return r


def _emp(pool, u):
    """Empirical inverse transform X = x_(ceil(u*n)), the v1 formula."""
    idx = np.maximum(1, np.ceil(u * len(pool))).astype(int) - 1
    return pool[np.minimum(idx, len(pool) - 1)]


def _mix_inv(u, w, mu, sd, hi):
    """Inverse of a normal-mixture CDF on y = ln x, truncated to (-inf, hi]; w, mu, sd are (n, K) or (K,)."""
    from scipy.special import ndtr
    w, mu, sd = (np.broadcast_to(np.asarray(v, float), (len(u),) + np.shape(v)[-1:]) for v in (w, mu, sd))
    F = lambda y: (w * ndtr((y[:, None] - mu) / sd)).sum(1)
    target = u * F(np.full(len(u), hi))
    lo = np.full(len(u), float((mu - 12 * sd).min()) if len(u) else 0.0); up = np.full(len(u), float(hi))
    for _ in range(60):
        mid = 0.5 * (lo + up); below = F(mid) < target
        lo = np.where(below, mid, lo); up = np.where(below, up, mid)
    return np.exp(0.5 * (lo + up))


class ServiceModel:
    """Service-time model; sample(hod, u) maps arrival hour of day + one uniform per car to dwell (h)."""

    def __init__(self, name, df, joint_k=JOINT_K, seed=SEED):
        if name not in SERVICES:
            raise ValueError(f"unknown service model {name!r}; choose from {SERVICES}")
        self.name, self.params = name, {}
        self.opt = name == "band_long_opt"
        rates, self.A, self.B = inputs(df)
        if name in ("band", "band_long", "band_long_opt"):
            self.pools = band_pools(df, long_stays=(name != "band"), opt=self.opt)
            self.params = {"band_n": [len(p) for p in self.pools], "band_mean_h": [float(p.mean()) for p in self.pools]}
        elif name == "mixA_lnB":
            from scipy import stats
            from sklearn.mixture import GaussianMixture
            g = GaussianMixture(4, n_init=20, random_state=seed).fit(np.log(self.A)[:, None])
            self.mixA = (g.weights_, g.means_.ravel(), np.sqrt(g.covariances_.ravel()))
            s, _, sc = stats.lognorm.fit(self.B, floc=0)
            self.lnB = (np.array([1.0]), np.array([np.log(sc)]), np.array([s]))
            self.params = {"mixA_w": self.mixA[0].tolist(), "mixA_mu": self.mixA[1].tolist(), "mixA_sd": self.mixA[2].tolist(),
                           "lnB_mu": float(np.log(sc)), "lnB_sd": float(s)}
        elif name == "jointGMM":
            from sklearn.mixture import GaussianMixture
            W = df[df.weekday & (df.dur <= MAXDUR)]
            arrh = (W.conn - W.conn.dt.normalize()).dt.total_seconds().values / 3600
            X = np.c_[arrh, np.log(W.dur.values)]
            g = GaussianMixture(joint_k, n_init=10, random_state=seed, covariance_type="full").fit(X)
            self.g = g
            self.params = {"K": joint_k, "w": g.weights_.tolist(), "mu": g.means_.tolist(), "cov": g.covariances_.tolist()}

    def sample(self, hod, u):
        if self.name == "AB":
            isA = (hod >= 5) & (hod < 12)
            return np.where(isA, _emp(self.A, u), _emp(self.B, u))
        if self.name in ("band", "band_long", "band_long_opt"):
            b = band_of(hod, self.opt); out = np.empty(len(u))
            for i, P in enumerate(self.pools):
                s = b == i; out[s] = _emp(P, u[s])
            return out
        hi = np.log(MAXDUR)
        if self.name == "mixA_lnB":
            isA = (hod >= 5) & (hod < 12); out = np.empty(len(u))
            out[isA] = _mix_inv(u[isA], *self.mixA, hi)
            out[~isA] = _mix_inv(u[~isA], *self.lnB, hi)
            return out
        from scipy.stats import norm                                  # jointGMM: ln y | arrival hour a
        w, mu, S = self.g.weights_, self.g.means_, self.g.covariances_
        a = np.asarray(hod, float)[:, None]
        pa = w * norm.pdf(a, mu[:, 0], np.sqrt(S[:, 0, 0])); pa /= pa.sum(1, keepdims=True)
        cm = mu[:, 1] + S[:, 0, 1] / S[:, 0, 0] * (a - mu[:, 0])
        cs = np.sqrt(S[:, 1, 1] - S[:, 0, 1] ** 2 / S[:, 0, 0])
        return _mix_inv(u, pa, cm, np.broadcast_to(cs, cm.shape), hi)


def draw(rates, A, B, rep, mult=1.0, model=None):
    """Arrival times (h) and service times (h) of replication rep; independent of c (CRN)."""
    rA = np.random.default_rng([rep, 1]); rS = np.random.default_rng([rep, 2])
    cum = np.concatenate([[0.0], np.cumsum(rates)])    # base cumulative expected arrivals at slot starts
    daytot = cum[-1]
    arr, L = [], 0.0
    while True:
        L += -np.log(1.0 - rA.random())                 # unit-rate exponential step (inverse transform)
        day = int(L // (daytot * mult)); rem = (L - day * daytot * mult) / mult
        k = int(np.searchsorted(cum[:48], rem, side="right") - 1)   # = Excel MATCH(rem, Cum, 1) - 1
        t = day * 24 + k * 0.5 + (rem - cum[k]) / rates[k] * 0.5
        if t >= HORIZON:
            break
        arr.append(t)
    arr = np.array(arr)
    u2 = rS.random(len(arr))
    hod = arr % 24
    if model is None or model.name == "AB":
        isA = (hod >= 5) & (hod < 12)
        idxA = np.maximum(1, np.ceil(u2 * len(A))).astype(int) - 1
        idxB = np.maximum(1, np.ceil(u2 * len(B))).astype(int) - 1
        svc = np.where(isA, A[np.minimum(idxA, len(A) - 1)], B[np.minimum(idxB, len(B) - 1)])
    else:
        svc = model.sample(hod, u2)
    return arr, svc, u2


def extra_outputs(arr, svc, start, c):
    """R7 outputs: P15 by arrival hour, bad-day rate, share of time all c busy, max queue, wait by arrival band."""
    w = (start - arr) * 60
    hr = np.floor(arr % 24).astype(int)
    n_h = np.bincount(hr, minlength=24); n15_h = np.bincount(hr, weights=(w > TARGET), minlength=24)
    day = np.floor(arr / 24).astype(int)
    bad = np.zeros(NDAYS, bool); bad[day[w > TARGET]] = True
    s, e = np.minimum(start, HORIZON), np.minimum(start + svc, HORIZON)
    ts = np.concatenate([s, e]); dl = np.concatenate([np.ones(len(s)), -np.ones(len(e))])
    o = np.lexsort((dl, ts)); ts, lev = ts[o], np.cumsum(dl[o])
    allbusy = float(np.diff(np.append(ts, HORIZON))[lev >= c].sum() / HORIZON)
    keep = start < HORIZON
    qt = np.concatenate([arr, start[keep]]); qd = np.concatenate([np.ones(len(arr)), -np.ones(keep.sum())])
    o = np.lexsort((qd, qt)); maxq = int(max(0, np.cumsum(qd[o]).max()))
    b = band_of(arr % 24)
    return dict(n_by_hour=n_h.tolist(), n15_by_hour=n15_h.astype(int).tolist(), bad_day_rate=float(bad.mean()),
                share_all_busy=allbusy, max_queue=maxq,
                wq_by_band=[float(w[b == i].mean()) if (b == i).any() else float("nan") for i in range(6)],
                n_by_band=[int((b == i).sum()) for i in range(6)])


def run_queue(arr, svc, c, occ_profile=False, extra=False):
    """FIFO c-server queue for given arrivals/services; returns (outputs, start times)."""
    free = [0.0] * c
    start = np.empty(len(arr))
    for i, (a, s) in enumerate(zip(arr, svc)):
        f = heapq.heappop(free); st = max(a, f); start[i] = st; heapq.heappush(free, st + s)
    w = (start - arr) * 60
    end = np.minimum(start + svc, HORIZON)
    busy = np.clip(end - np.minimum(start, HORIZON), 0, None).sum() / HORIZON
    out = dict(N=int(len(arr)), Wq=float(w.mean()), P0=float((w > 1e-9).mean()),
               P15=float((w > TARGET).mean()), Busy=float(busy), Util=float(busy / c),
               W95=float(np.quantile(w, 0.95)))
    if occ_profile:
        prof = np.zeros(48)
        for d in range(NDAYS):
            for k in range(48):
                tau = d * 24 + k * 0.5
                prof[k] += ((start <= tau) & (start + svc > tau)).sum()
        out["occ"] = (prof / NDAYS).tolist()
    if extra:
        out["extra"] = extra_outputs(arr, svc, start, c)
    return out, start


def replicate(rates, A, B, c, rep, mult=1.0, occ_profile=False, model=None, extra=False):
    """One replication. model=None (or an AB ServiceModel) gives the v1 service model bit for bit."""
    arr, svc, u2 = draw(rates, A, B, rep, mult, model)
    out, _ = run_queue(arr, svc, c, occ_profile, extra)
    return out, arr, svc, u2


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="EV charging DES engine v2")
    ap.add_argument("data", nargs="?", default=DATA, help="raw ACN JSON")
    ap.add_argument("--service", choices=SERVICES, default="band_long")
    ap.add_argument("--joint-k", type=int, default=JOINT_K, help="components of the joint GMM (jointGMM only)")
    ap.add_argument("--rates-file", default=None, help="48 half-hour rates CSV (e.g. data/derived/rates_designday.csv)")
    ap.add_argument("--out", default=None, help="output JSON (default engine_outputs[_<service>].json)")
    args = ap.parse_args()
    DATA = args.data
    df = load(); rates, A, B = inputs(df)
    if args.rates_file:
        rates = load_rates(args.rates_file)
    model = None if args.service == "AB" else ServiceModel(args.service, df, joint_k=args.joint_k)
    run = lambda c, r, m, **kw: replicate(rates, A, B, c, r, m, model=model, **kw)
    res = {"rates": rates.tolist(), "nA": len(A), "nB": len(B)}
    if model is not None:
        res["service"] = args.service; res["service_params"] = model.params; res["seed"] = SEED
    OPTIONS = [52, 46, 42, 38]
    res["pilot"] = {c: [run(c, r, 1.3)[0] for r in range(1, 11)] for c in OPTIONS}
    NFINAL = 60
    res["final"] = {c: [run(c, r, 1.3)[0] for r in range(1, NFINAL + 1)] for c in OPTIONS}
    res["sens"] = {m: [run(52, r, m)[0] for r in range(1, NFINAL + 1)]
                   for m in [1.0, 1.3, 1.6, 1.8, 2.0, 2.2]}
    v = [run(52, r, 1.0, occ_profile=True)[0] for r in range(1, 11)]
    res["valid"] = v
    res["validN"] = 10
    # U streams of replication 1 for the Excel replica sheet
    rA = np.random.default_rng([1, 1]); u1 = rA.random(4500)
    rS = np.random.default_rng([1, 2]); u2 = rS.random(4500)
    res["u1"] = u1.tolist(); res["u2"] = u2.tolist()
    o, a, sv, _ = run(52, 1, 1.3)
    res["rep1_first"] = {"arr": a[:25].tolist(), "svc": sv[:25].tolist()}
    out = args.out or ("engine_outputs.json" if args.service == "AB" else f"engine_outputs_{args.service}.json")
    json.dump(res, open(out, "w"))
    for c in OPTIONS:
        f = res["final"][c]
        print(c, np.mean([x["Wq"] for x in f]), np.mean([x["P15"] for x in f]), np.std([x["P15"] for x in f], ddof=1))
